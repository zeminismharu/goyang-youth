export function fmtMinutes(m) {
  if (m == null) return '-';
  const h = Math.floor(m / 60);
  const mm = m % 60;
  if (!h) return `${mm}분`;
  return mm ? `${h}시간 ${mm}분` : `${h}시간`;
}
